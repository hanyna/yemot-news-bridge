entries = []
seen = set()
for cat, block in cats.items():
    lines=[]
    for ln in block.strip().split("\n"):
        ln=ln.strip()
        if not ln or "=" not in ln: continue
        k,v = ln.split("=",1)
        k=k.strip(); v=v.strip()
        if k in seen: continue
        # entries that map to identical text add nothing — skip (except explicit removals)
        if k == v: continue
        seen.add(k)
        lines.append((k,v))
    entries.append((cat,lines))

def gostr(s):
    return "`"+s+"`" if "`" not in s else '"'+s.replace('"','\\"')+'"'
out = ["package main","","// מילון הגייה מורחב — נוצר אוטומטית (scripts/gendict.py). כל שורה: מה כתוב → מה להקריא.",
       "// ערך ריק = להשמיט. להוספת מילה: להוסיף שורה לקטגוריה המתאימה ב-gendict.py ולהריץ אותו,",
       "// או להוסיף ישירות כאן.","","var pronunciationMore = map[string]string{"]
total=0
for cat,lines in entries:
    out.append("\t// "+cat)
    for k,v in lines:
        out.append("\t%s: %s," % (gostr(k), '"'+v.replace('"','\\"')+'"'))
        total+=1
out.append("}")
open("dictionary.go","w",encoding="utf-8").write("\n".join(out)+"\n")
print("entries:", total)
