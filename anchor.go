// voiceText: הטקסט שנשלח לקול — עם שמות הכתבים מנוקדים.
func voiceText(s string) string {
	for _, r := range nameRules {
		for i := 0; i < 2; i++ {
			s = r.re.ReplaceAllString(s, "${1}${2}"+r.with+"${3}")
		}
	}
	return s
}

// reLaugh: "חחח", "חחחח", "חהחה" — המנוע מקריא אותם כצחוק. נמחקים מההקראה.
var reLaugh = regexp.MustCompile(`(^|[^\p{L}])(?:ח{3,}|(?:חה){2,}ח?)($|[^\p{L}])`)

func dropLaugh(s string) string {
	for i := 0; i < 2; i++ {
		s = reLaugh.ReplaceAllString(s, "${1} ${2}")
	}
	return strings.TrimSpace(s)
}
